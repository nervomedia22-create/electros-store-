-- 1. Enable UUID Extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. Products Table
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    title_en TEXT,
    category TEXT NOT NULL CHECK (category IN ('phones', 'laptops', 'tvs', 'audio', 'watches', 'gaming', 'accessories', 'cameras')),
    price NUMERIC(10, 2) NOT NULL,
    old_price NUMERIC(10, 2),
    discount INT,
    rating NUMERIC(2, 1) DEFAULT 5.0,
    reviews_count INT DEFAULT 1,
    image TEXT NOT NULL,
    express BOOLEAN DEFAULT true,
    stock INT DEFAULT 10,
    stock_percent INT DEFAULT 90,
    brand TEXT DEFAULT 'ElectroTech',
    is_flash BOOLEAN DEFAULT false,
    specs TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Users Table (Customer & Admin Accounts)
CREATE TABLE IF NOT EXISTS public.users (
    id TEXT PRIMARY KEY DEFAULT ('usr-' || substr(md5(random()::text), 1, 10)),
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    phone TEXT,
    role TEXT DEFAULT 'customer' CHECK (role IN ('customer', 'admin')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Orders Table
CREATE TABLE IF NOT EXISTS public.orders (
    id TEXT PRIMARY KEY, -- e.g. "EG-10842"
    customer_name TEXT NOT NULL,
    customer_phone TEXT NOT NULL,
    customer_email TEXT,
    customer_address TEXT NOT NULL,
    city TEXT NOT NULL,
    payment_method TEXT DEFAULT 'cod' CHECK (payment_method IN ('cod', 'card', 'fawry', 'valu')),
    total_amount NUMERIC(12, 2) NOT NULL,
    status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'processing', 'shipped', 'delivered', 'cancelled')),
    tracking_code TEXT NOT NULL,
    courier_name TEXT DEFAULT 'بوسطة إكسبريس (جاري تعيين المندوب)',
    courier_phone TEXT DEFAULT '19888',
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. Order Items Table
CREATE TABLE IF NOT EXISTS public.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id TEXT REFERENCES public.orders(id) ON DELETE CASCADE,
    product_id BIGINT,
    title TEXT NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    quantity INT DEFAULT 1,
    image TEXT
);

-- 6. Order Status History Table
CREATE TABLE IF NOT EXISTS public.order_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id TEXT REFERENCES public.orders(id) ON DELETE CASCADE,
    status TEXT NOT NULL,
    note TEXT,
    timestamp TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- =====================================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- =====================================================================

ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_history ENABLE ROW LEVEL SECURITY;

-- Products: Allow everyone to read products, authenticated admins to modify
CREATE POLICY "Public Read Products" ON public.products FOR SELECT USING (true);
CREATE POLICY "Admin All Products" ON public.products FOR ALL USING (true);

-- Orders: Allow public creation and tracking by order id
CREATE POLICY "Public Create Orders" ON public.orders FOR INSERT WITH CHECK (true);
CREATE POLICY "Public Read Orders" ON public.orders FOR SELECT USING (true);
CREATE POLICY "Admin Update Orders" ON public.orders FOR UPDATE USING (true);

-- Order Items & History: Allow select and insert
CREATE POLICY "Public Insert Order Items" ON public.order_items FOR INSERT WITH CHECK (true);
CREATE POLICY "Public Read Order Items" ON public.order_items FOR SELECT USING (true);
CREATE POLICY "Public Insert Order History" ON public.order_history FOR INSERT WITH CHECK (true);
CREATE POLICY "Public Read Order History" ON public.order_history FOR SELECT USING (true);

-- Users: Allow read and insert
CREATE POLICY "Users Read" ON public.users FOR SELECT USING (true);
CREATE POLICY "Users Insert" ON public.users FOR INSERT WITH CHECK (true);

